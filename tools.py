def extract_clauses(client: "LLMClient", contract_text: str, contract_type: str) -> str:
    """从合同全文提取结构化条款。由 Agent 在审查第一步调用。"""
    from prompts import EXTRACT_CLAUSES_SYSTEM, EXTRACT_CLAUSES_USER

    text = contract_text[:8000]  # 截断超长合同
    system = EXTRACT_CLAUSES_SYSTEM.format(contract_type=contract_type)
    user = EXTRACT_CLAUSES_USER.format(contract_type=contract_type, contract_text=text)
    return client.call(system, user, max_tokens=1024)


def analyze_single_clause(
    client: "LLMClient",
    clause_text: str,
    category: str,
    contract_type: str,
    clause_position: str = "",
    regulation_context: str = "",
) -> str:
    """深度分析单条条款。Agent 可以在查完法规后调用此函数。"""
    from prompts import ANALYZE_SINGLE_CLAUSE_SYSTEM, ANALYZE_SINGLE_CLAUSE_USER

    user = ANALYZE_SINGLE_CLAUSE_USER.format(
        category=category,
        position=clause_position or "未标注",
        contract_type=contract_type,
        clause_text=clause_text[:2000],
        regulation_context=regulation_context[:3000] or "无",
    )
    return client.call(ANALYZE_SINGLE_CLAUSE_SYSTEM, user, max_tokens=1024)


def generate_final_report(
    client: "LLMClient", risk_findings_json: str, contract_type: str
) -> str:
    """汇总所有风险发现，生成最终审查报告。Agent 在分析完成后调用。"""
    from datetime import date
    from prompts import GENERATE_REPORT_SYSTEM, GENERATE_REPORT_USER

    system = GENERATE_REPORT_SYSTEM.format(
        contract_type=contract_type, today=date.today().strftime("%Y-%m-%d")
    )
    user = GENERATE_REPORT_USER.format(risk_analysis=risk_findings_json[:6000])
    return client.call(system, user, max_tokens=3072)


def check_completeness(
    client: "LLMClient", clauses_json: str, contract_type: str
) -> str:
    """检查合同条款完整性，找出缺失的必要条款。调用 LLM。"""
