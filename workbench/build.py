#!/usr/bin/env python3
"""合同工作台 · 零依赖构建脚本

用法：
    python workbench/build.py              # 生成数据 + 内联 → dist/index.html
    python workbench/build.py --data-only  # 只生成 src/data/samples.js / knowledge.js
    python workbench/build.py --check      # 只检查 dist 产物
"""

from __future__ import annotations

import base64
import json
import sys
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parent
SRC = ROOT / "src"
DIST = ROOT / "dist"
VENDOR = ROOT / "vendor"

SAMPLE_FILES = [
    ("lease", "房屋租赁合同", "sample_lease.txt"),
    ("employment", "劳动合同", "sample_employment.txt"),
    ("sales", "买卖合同", "sample_sales.txt"),
    ("service", "服务合同", "sample_service.txt"),
    ("cooperation", "合作协议", "sample_cooperation.txt"),
    ("loan", "借款合同", "sample_loan.txt"),
]

KNOWLEDGE_FILES = [
    ("regulation", "regulation.json"),
    ("caseLaw", "case_law.json"),
    ("localPolicy", "local_policy.json"),
    ("taxRule", "tax_rule.json"),
    ("webKb", "web_kb.json"),
]

SCRIPT_ORDER = [
    "data/rules.js",
    "data/samples.js",
    "data/knowledge.js",
    "prompts.js",
    "llm.js",
    "pipeline.js",
    "docx.js",
    "storage.js",
    "rule_store.js",
    "ledger.js",
    "file_parser.js",
    "app.js",
]

VENDOR_FILES = {
    "pdf_main": VENDOR / "pdfjs" / "pdf.min.mjs",
    "pdf_worker": VENDOR / "pdfjs" / "pdf.worker.min.mjs",
    "mammoth": VENDOR / "mammoth" / "mammoth.browser.min.js",
}


def js_literal(value) -> str:
    return json.dumps(value, ensure_ascii=False)


def generate_data() -> None:
    data_dir = SRC / "data"
    data_dir.mkdir(parents=True, exist_ok=True)

    samples = []
    for key, name, filename in SAMPLE_FILES:
        path = REPO / filename
        text = path.read_text(encoding="utf-8")
        samples.append({"key": key, "name": name, "file": filename, "text": text})

    samples_js = (
        "/* AUTO-GENERATED by workbench/build.py — 请勿手改 */\n"
        "(function (root) {\n"
        "  const WB = (root.WB = root.WB || {});\n"
        f"  WB.SAMPLES = {js_literal(samples)};\n"
        "})(globalThis);\n"
    )
    (data_dir / "samples.js").write_text(samples_js, encoding="utf-8")

    knowledge = {}
    for key, filename in KNOWLEDGE_FILES:
        path = REPO / "knowledge" / filename
        if path.exists():
            knowledge[key] = json.loads(path.read_text(encoding="utf-8"))

    knowledge_js = (
        "/* AUTO-GENERATED by workbench/build.py — 请勿手改 */\n"
        "(function (root) {\n"
        "  const WB = (root.WB = root.WB || {});\n"
        f"  WB.KNOWLEDGE = {js_literal(knowledge)};\n"
        "})(globalThis);\n"
    )
    (data_dir / "knowledge.js").write_text(knowledge_js, encoding="utf-8")

    print(f"[data] samples: {len(samples)} 份")
    print(f"[data] knowledge: {', '.join(knowledge.keys())}")


def inline_file(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def build() -> int:
    index_path = SRC / "index.html"
    if not index_path.exists():
        print("[build] 缺少 src/index.html", file=sys.stderr)
        return 1

    html = inline_file(index_path)
    placeholders = ("<!-- BUILD:STYLES -->", "<!-- BUILD:VENDOR -->", "<!-- BUILD:SCRIPTS -->")
    if any(p not in html for p in placeholders):
        print("[build] index.html 缺少 BUILD 占位符", file=sys.stderr)
        return 1

    for name, path in VENDOR_FILES.items():
        if not path.exists():
            print(f"[build] 缺少解析器：{path}（请先放置 pdf.js / mammoth 产物）", file=sys.stderr)
            return 1

    css = inline_file(SRC / "styles.css")
    html = html.replace("<!-- BUILD:STYLES -->", f"<style>\n{css}\n</style>")

    pdf_main = base64.b64encode(VENDOR_FILES["pdf_main"].read_bytes()).decode("ascii")
    pdf_worker = base64.b64encode(VENDOR_FILES["pdf_worker"].read_bytes()).decode("ascii")
    mammoth = inline_file(VENDOR_FILES["mammoth"]).replace("</script", "<\\/script")
    vendor_html = "\n".join(
        [
            f'<script type="text/plain" id="pdfjs-main">{pdf_main}</script>',
            f'<script type="text/plain" id="pdfjs-worker">{pdf_worker}</script>',
            f"<script>\n{mammoth}\n</script>",
        ]
    )
    html = html.replace("<!-- BUILD:VENDOR -->", vendor_html)

    scripts = []
    for rel in SCRIPT_ORDER:
        path = SRC / rel
        if not path.exists():
            print(f"[build] 缺少脚本：{rel}", file=sys.stderr)
            return 1
        # 防止内联脚本里的 </script> 提前闭合标签
        code = inline_file(path).replace("</script", "<\\/script")
        scripts.append(f"<script>\n{code}\n</script>")

    html = html.replace("<!-- BUILD:SCRIPTS -->", "\n".join(scripts))

    DIST.mkdir(parents=True, exist_ok=True)
    out = DIST / "index.html"
    out.write_text(html, encoding="utf-8")

    size = out.stat().st_size
    print(f"[build] 已生成 {out}（{size / 1024:.1f} KB）")
    return 0


def check() -> int:
    out = DIST / "index.html"
    ok = True
    if not out.exists():
        print("[check] dist/index.html 不存在", file=sys.stderr)
        return 1

    html = out.read_text(encoding="utf-8")
    size = out.stat().st_size
    if size >= 4 * 1024 * 1024:
        print(f"[check] ✗ 体积超限：{size / 1024:.1f} KB >= 4096 KB", file=sys.stderr)
        ok = False
    else:
        print(f"[check] ✓ 体积 {size / 1024:.1f} KB < 4096 KB")

    checks = [
        ("无外部脚本", "<script src=" not in html and "<script src=" not in html),
        ("无外部样式", '<link rel="stylesheet"' not in html),
        ("无 http 外链导入", "@import url(http" not in html),
        ("含 CSP", "Content-Security-Policy" in html),
        (
            "占位符已替换",
            all(
                p not in html
                for p in (
                    "<!-- BUILD:STYLES -->",
                    "<!-- BUILD:VENDOR -->",
                    "<!-- BUILD:SCRIPTS -->",
                )
            ),
        ),
        ("含免责声明", "不构成法律意见" in html),
        ("含示例合同", "sample_lease.txt" in html),
        ("RULES 数量 ≥ 60", _count_rules(html) >= 60),
        ("含 5 步流水线", "WB.runPipeline" in html),
        ("含 PDF 解析器", 'id="pdfjs-main"' in html and 'id="pdfjs-worker"' in html),
        ("含 DOCX 解析器", "mammoth.extractRawText" in html),
        ("含文件解析入口", "WB.parseFile" in html),
        ("含合同台账", 'id="view-ledger"' in html and "WB.Ledger" in html),
        ("含规则编辑器", 'id="view-rules"' in html and "WB.RuleStore" in html),
    ]
    for name, passed in checks:
        print(f"[check] {'✓' if passed else '✗'} {name}")
        ok = ok and passed

    return 0 if ok else 1


def _count_rules(html: str) -> int:
    # 规则以 r("r_xxx", ...) 的形式出现
    return html.count('r("r_')


def main() -> int:
    args = set(sys.argv[1:])
    if "--check" in args:
        return check()
    generate_data()
    if "--data-only" in args:
        return 0
    rc = build()
    if rc:
        return rc
    return check()


if __name__ == "__main__":
    raise SystemExit(main())
