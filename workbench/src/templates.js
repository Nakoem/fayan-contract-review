  function findTemplate(key) {
    return TEMPLATES.find((item) => item.key === key) || null;
  }

  function templateMeta(key) {
    return findTemplate(key) || TEMPLATES[0];
  }

  function fieldPlaceholder(field) {
    if (!field) return "【待填写】";
    if (field.optional) return "无";
    return "【待填写：" + field.label + "】";
  }

  function fillTemplate(body, fields, values) {
    const map = {};
    (fields || []).forEach((field) => { map[field.key] = field; });
    return String(body || "").replace(/\{\{([a-zA-Z0-9_]+)\}\}/g, (_match, key) => {
      const raw = String((values || {})[key] || "").trim();
      if (raw) return raw;
      return fieldPlaceholder(map[key]);
    });
  }

  function buildTemplateText(key, values) {
    const meta = findTemplate(key);
    if (!meta || !meta.available) return "";
    const text = fillTemplate(meta.body, meta.fields, values || {}).trim();
    if (!text) return "";
    return text + "\n\n" + DISCLAIMER;
  }

  function buildTemplateHtml(input) {
    const data = input || {};
    return WB.buildDocumentHtml({
      text: data.text,
      meta: data.meta || "合同范本 · 生成后请由律师复核",
    });
  }

  function buildTemplateDocx(input) {
    return WB.buildDocxFromHtml(buildTemplateHtml(input || {}));
  }

  WB.TEMPLATES = TEMPLATES;
  WB.templateMeta = templateMeta;
  WB.buildTemplateText = buildTemplateText;
  WB.buildTemplateHtml = buildTemplateHtml;
  WB.buildTemplateDocx = buildTemplateDocx;
