"""构建产物检查。

先运行 build.py，再检查 dist/index.html 的体积、外链与必备内容。
"""

from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
DIST = ROOT / "dist" / "index.html"
BUILD = ROOT / "build.py"


@pytest.fixture(scope="module")
def html() -> str:
    subprocess.run(
        [sys.executable, str(BUILD)],
        check=True,
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    assert DIST.exists(), "构建后没有 dist/index.html"
    return DIST.read_text(encoding="utf-8")


def test_size_under_limit(html):
    size = DIST.stat().st_size
    assert size < 4 * 1024 * 1024, f"体积超限：{size / 1024:.1f} KB"


def test_no_external_scripts(html):
    assert "<script src=" not in html and "<script src=" not in html.lower()


def test_no_external_stylesheets(html):
    assert '<link rel="stylesheet"' not in html.lower()


def test_no_remote_imports(html):
    assert "@import url(http" not in html.lower()


def test_csp_present(html):
    assert "Content-Security-Policy" in html


def test_build_placeholders_removed(html):
    assert "<!-- BUILD:STYLES -->" not in html
    assert "<!-- BUILD:VENDOR -->" not in html
    assert "<!-- BUILD:SCRIPTS -->" not in html


def test_disclaimer_present(html):
    assert "不构成法律意见" in html
    assert "执业律师复核" in html


def test_samples_embedded(html):
    for name in (
        "sample_lease.txt",
        "sample_employment.txt",
        "sample_sales.txt",
        "sample_service.txt",
        "sample_cooperation.txt",
        "sample_loan.txt",
    ):
        assert name in html, f"缺少示例：{name}"


def test_rules_embedded(html):
    assert html.count('r("r_') >= 100, "内置规则不足 100 条"
    assert "WB.RULES_META" in html, "缺少规则法条核对信息"


def test_pipeline_embedded(html):
    assert "WB.runPipeline" in html
    assert "WB.highlightContract" in html
    assert "WB.buildDocHtml" in html
    assert "WordSection1" in html


def test_review_stance_embedded(html):
    assert 'id="review-stance"' in html
    assert "WB.STANCES" in html
    assert "stanceLabel" in html


def test_docx_export_embedded(html):
    assert "WB.buildDocx" in html
    assert "application/vnd.openxmlformats-officedocument.wordprocessingml.document" in html
    assert "导出 .docx" in html


def test_rule_editor_embedded(html):
    assert 'id="view-rules"' in html
    assert "WB.RuleStore" in html
    assert 'id="rule-drawer"' in html


def test_file_parsers_embedded(html):
    assert 'id="pdfjs-main"' in html
    assert 'id="pdfjs-worker"' in html
    assert "WB.parseFile" in html
    assert "mammoth.extractRawText" in html


def test_vendor_licenses_present():
    assert (ROOT / "vendor" / "pdfjs" / "LICENSE").exists()
    assert (ROOT / "vendor" / "mammoth" / "LICENSE").exists()


def test_autogenerated_headers():
    for name in ("samples.js", "knowledge.js"):
        text = (ROOT / "src" / "data" / name).read_text(encoding="utf-8")
        assert "AUTO-GENERATED" in text, f"{name} 缺少自动生成标记"


def test_no_missing_scripts():
    for rel in (
        "storage.js",
        "rule_store.js",
        "file_parser.js",
        "app.js",
        "prompts.js",
        "llm.js",
        "pipeline.js",
        "docx.js",
    ):
        assert (ROOT / "src" / rel).exists(), f"缺少 {rel}"


def test_python_available():
    # 构建脚本自身可执行
    assert shutil.which(sys.executable)
